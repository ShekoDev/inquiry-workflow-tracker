// ---------------- Activity log ----------------
export type ActivityAction =
  | 'CREATE' | 'UPDATE' | 'DELETE' | 'VIEW' | 'LOGIN' | 'LOGOUT' | 'LOGIN_FAILED'
  | 'APPROVE' | 'REJECT' | 'EXPORT' | 'PERMISSION_CHANGE' | 'STATUS_CHANGE' | 'ASSIGN';

/** what a log entry needs in order to be reversible from the activity log */
export type UndoPayload =
  | { kind: 'restore'; trashId: string }
  | { kind: 'fields'; path: string; values: Record<string, unknown> };

/** a deleted bundle held for 30 days so it can be put back */
export interface TrashItem {
  id: string;
  module: string;
  label: string;
  recordId?: string;
  docCount: number;
  docs: { path: string; data: Record<string, unknown> }[];
  deletedAt: Timestamp;
  deletedBy: string;
  deletedByName: string;
  expiresAt: Timestamp;
}

export interface ActivityLog {
  id: string;
  timestamp: Timestamp;
  userId: string;
  userName: string;
  userEmail: string;
  roleId: string;
  action: ActivityAction;
  module: string;
  recordId?: string;
  recordLabel?: string;
  field?: string;
  oldValue?: string;
  newValue?: string;
  descriptionAr: string;
  descriptionEn: string;
  userAgent?: string;
  sessionId?: string;
  /** present when the action can be reversed with one click */
  undo?: UndoPayload;
  undoneAt?: Timestamp;
  undoneBy?: string;
  undoneByName?: string;
}

