// ---------------- Notifications ----------------
export type NotificationType = 'system' | 'broadcast' | 'alert';
export type NotificationCategory = 'today' | 'week' | 'urgent';

export interface AppNotification {
  id: string;
  userId: string;
  titleAr: string;
  titleEn: string;
  bodyAr?: string;
  bodyEn?: string;
  link?: string;
  read: boolean;
  level: 'info' | 'warning' | 'danger' | 'success';
  type: NotificationType; // 'system' = deadline alert, 'broadcast' = رسالة من المدير, 'alert' = نبيهات أخرى
  category?: NotificationCategory; // للتصنيف: اليوم، الاسبوع، مهمة جداً
  createdAt: Timestamp;
  expiresAt?: Timestamp; // متى تختفي الرسالة
  sentBy?: string; // من أرسلها (لمدير النظام)
  sentByName?: string;
  recipients?: string[]; // قائمة المستخدمين المُستهدفين
  readBy?: Record<string, Timestamp>; // {userId: readAt}
  deletedBy?: Record<string, Timestamp>; // {userId: deletedAt} - لتتبع من حذفها
}

